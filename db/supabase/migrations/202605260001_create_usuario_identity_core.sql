create schema if not exists internal;

revoke all on schema internal from public;

create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text,
  hierarchy_level smallint not null default 100,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.permissions (
  id bigint generated by default as identity primary key,
  role_id bigint not null references public.roles(id) on delete cascade,
  app_slug text not null,
  can_access boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  unique (role_id, app_slug)
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  name text not null,
  avatar_url text,
  role_id bigint not null references public.roles(id),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role_id bigint not null references public.roles(id),
  assigned_by uuid references public.profiles(id),
  assigned_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id),
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  ip_address text,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_permissions_app_slug on public.permissions(app_slug);
create index if not exists idx_profiles_role_id on public.profiles(role_id);
create index if not exists idx_user_roles_user_id on public.user_roles(user_id);
create index if not exists idx_user_roles_role_id on public.user_roles(role_id);
create index if not exists idx_audit_log_user_id on public.audit_log(user_id);
create index if not exists idx_audit_log_created_at on public.audit_log(created_at desc);

create or replace function internal.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists trg_profiles_set_updated_at on public.profiles;
create trigger trg_profiles_set_updated_at
before update on public.profiles
for each row
execute function internal.set_updated_at();

create or replace function internal.is_admin(user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = user_id
      and r.slug = 'admin'
  );
$$;

create or replace function internal.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  default_role_id bigint;
  profile_name text;
begin
  select id into default_role_id
  from public.roles
  where slug = 'usuario'
  limit 1;

  if default_role_id is null then
    raise exception 'Role "usuario" is required before creating profiles';
  end if;

  profile_name := coalesce(
    nullif(new.raw_user_meta_data ->> 'name', ''),
    split_part(coalesce(new.email, ''), '@', 1),
    'Usuario'
  );

  insert into public.profiles (id, email, name, role_id)
  values (new.id, coalesce(new.email, ''), profile_name, default_role_id)
  on conflict (id) do update
  set email = excluded.email,
      name = coalesce(excluded.name, public.profiles.name),
      role_id = coalesce(public.profiles.role_id, excluded.role_id),
      updated_at = timezone('utc', now());

  insert into public.user_roles (user_id, role_id, assigned_by)
  values (new.id, default_role_id, null);

  insert into public.audit_log (user_id, action, metadata)
  values (
    new.id,
    'user_created',
    jsonb_build_object('source', 'auth.users_trigger')
  );

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row
execute function internal.handle_new_user();

