insert into public.roles (slug, name, description, hierarchy_level)
values
  ('admin', 'Administrador', 'Control total del ecosistema', 1),
  ('sacerdote', 'Sacerdote', 'Rol pastoral con permisos específicos', 20),
  ('coordinador', 'Coordinador', 'Gestión operativa de servicios y comunidades', 40),
  ('usuario', 'Usuario', 'Acceso básico a aplicaciones autorizadas', 100)
on conflict (slug) do update
set
  name = excluded.name,
  description = excluded.description,
  hierarchy_level = excluded.hierarchy_level;

with role_map as (
  select id, slug from public.roles
),
app_map as (
  select unnest(array['portal', 'biblia', 'calendario', 'usuario']) as app_slug
)
insert into public.permissions (role_id, app_slug, can_access)
select
  r.id,
  a.app_slug,
  case
    when r.slug = 'admin' then true
    when r.slug = 'sacerdote' then a.app_slug in ('portal', 'biblia', 'calendario', 'usuario')
    when r.slug = 'coordinador' then a.app_slug in ('portal', 'calendario', 'usuario')
    when r.slug = 'usuario' then a.app_slug in ('portal', 'biblia', 'calendario')
    else false
  end as can_access
from role_map r
cross join app_map a
on conflict (role_id, app_slug) do update
set can_access = excluded.can_access;

insert into public.profiles (id, email, name, role_id)
select
  u.id,
  coalesce(u.email, ''),
  coalesce(
    nullif(u.raw_user_meta_data ->> 'name', ''),
    split_part(coalesce(u.email, ''), '@', 1),
    'Usuario'
  ),
  (select id from public.roles where slug = 'usuario')
from auth.users u
where not exists (
  select 1 from public.profiles p where p.id = u.id
);
